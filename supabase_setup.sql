-- 1. Create the 'todos' table
CREATE TABLE IF NOT EXISTS todos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  is_completed BOOLEAN DEFAULT FALSE,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. Enable Row Level Security (RLS)
ALTER TABLE todos ENABLE ROW LEVEL SECURITY;

-- 3. Create a public access policy for CRUD demonstration
-- NOTE: In production apps with user authentication, you would restrict rows
-- using auth.uid() = user_id. For this simple demo, we permit all CRUD operations:
DROP POLICY IF EXISTS "Allow public CRUD operations" ON todos;

CREATE POLICY "Allow public CRUD operations" 
ON todos 
FOR ALL 
TO public 
USING (true) 
WITH CHECK (true);

